/**
 * Posted meta line.
 */
function dreamam_posted_on() {
	$time_string = sprintf(
		'<time class="entry-date published updated" datetime="%1$s">%2$s</time>',
		esc_attr( get_the_date( DATE_W3C ) ),
		esc_html( get_the_date() )
	);
	printf(
		'<span class="posted-on">%s</span>',
		$time_string // phpcs:ignore
	);
}

/**
 * Posted category chips.
 */
function dreamam_post_categories() {
	if ( 'post' !== get_post_type() ) {
		return;
	}
	$categories_list = get_the_category_list( ' ' );
	if ( $categories_list ) {
		printf(
			'<span class="cat-links">%s</span>',
			$categories_list // phpcs:ignore
		);
	}
}

/**
 * Pagination helper.
 */
function dreamam_pagination() {
	$pagination = paginate_links( array(
		'prev_text' => '‹ 前へ',
		'next_text' => '次へ ›',
		'type'      => 'array',
	) );
	if ( ! $pagination ) {
		return;
	}
	echo '<nav class="pagination" aria-label="pagination">';
	foreach ( $pagination as $page ) {
		echo $page; // phpcs:ignore
	}
	echo '</nav>';
}

